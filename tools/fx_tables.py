# name, RGB; outline is black except for black text (white outline)
COLOURS = [
    ("WHITE", (255, 255, 255)),
    ("YELLOW", (255, 204, 0)),
    ("RED", (232, 32, 40)),
    ("BLUE", (40, 96, 240)),
    ("GREEN", (40, 200, 72)),
    ("PINK", (255, 112, 184)),
    ("BLACK", (0, 0, 0)),
]


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def yuv(r, g, b):
    y = 0.299 * r + 0.587 * g + 0.114 * b
    u = 128 + 0.564 * (b - y)
    v = 128 + 0.713 * (r - y)
    c = lambda x: max(0, min(255, int(round(x))))
    return c(y), c(u), c(v)


def glyph_columns(rows):
    rows = rows.split()
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), rows
    return [sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5)]


def glyph_index(ch):
    for i, (name, _) in enumerate(GLYPHS):
        if name == ch:
            return i
    raise KeyError(ch)


def render_header():
    out = ["/* generated by tools/fx_tables.py - do not edit */", "#pragma once",
           "#define NGLYPH %d" % len(GLYPHS), "#define GLYPH_DONE %d" % (len(GLYPHS) - 1),
           "#define GLYPH_SPACE %d" % glyph_index(" "), "#define GLYPH_0 %d" % glyph_index("0"),
           "#define GLYPH_COLON %d" % glyph_index(":"),
           "#define NCOLOR %d" % len(COLOURS),
           "static const u8 FONT[NGLYPH][5] = {"]
    for name, rows in GLYPHS:
        out.append("  {%s}, /* %s */" % (", ".join("0x%02X" % c for c in glyph_columns(rows)), name))
    out.append("};")
    cos = [int(round(math.cos(math.radians(15 * k)) * 16384)) for k in range(24)]
    out.append("static const s16 COS24[24] = {%s};" % ", ".join(map(str, cos)))
    pal = []
    for name, (r, g, b) in COLOURS:
        o = (255, 255, 255) if (r, g, b) == (0, 0, 0) else (0, 0, 0)
        y, u, v = yuv(r, g, b)
        oy, ou, ov = yuv(*o)
        pal.append("  {0x%04X, 0x%04X, %d, %d, %d, %d, %d, %d}, /* %s */" %
                   (rgb565(r, g, b), rgb565(*o), y, u, v, oy, ou, ov, name))
    out.append("struct pal { u16 c565, o565; u8 y, u, v, oy, ou, ov; };")
    out.append("static const struct pal PAL[NCOLOR] = {")
    out += pal
    out.append("};")
    return "\n".join(out) + "\n"


def icon_rgb565(name="T", fg=(255, 255, 255), bg=(0, 0, 0)):
    """16x16 icon: the glyph scaled x2, centred, as RGB565 little-endian."""
    import struct
    cols = glyph_columns(dict(GLYPHS)[name])
    px = [rgb565(*bg)] * 256
    for gx in range(5):
        for gy in range(7):
            if cols[gx] >> gy & 1:
                for dx in range(2):
                    for dy in range(2):
                        x, y = 3 + gx * 2 + dx, 1 + gy * 2 + dy
                        px[y * 16 + x] = rgb565(*fg)
    return struct.pack("<256H", *px)


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else "fx_text/fx_tables.h"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(render_header())
    print("wrote", path)
